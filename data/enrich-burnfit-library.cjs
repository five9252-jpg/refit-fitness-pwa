function equipment(name, category) {
  const n = name.replace(/\s/g, '');
  if (n.includes('케틀벨')) return '케틀벨';
  if (n.includes('덤벨')) return '덤벨';
  if (n.includes('스미스머신')) return '스미스 머신';
  if (n.includes('트랩바')) return '트랩바';
  if (n.includes('이지바')) return 'EZ 바';
  if (n.includes('바벨')) return '바벨';
  if (n.includes('케이블') || n.includes('풀리')) return '케이블';
  if (n.includes('머신') || n.includes('레그프레스') || n.includes('레그컬') || n.includes('레그익스텐션')) return '머신';
  if (n.includes('보수볼')) return '보수볼';
  if (n.includes('메디신볼') || n.includes('월볼')) return '메디신볼';
  if (n.includes('배틀링로프')) return '로프';
  if (n.includes('맨몸') || n.includes('에어스쿼트') || n.includes('푸시업') || n.includes('플랭크') || n.includes('크런치')) return '맨몸';
  if (n.includes('트레드밀')) return '트레드밀';
  if (n.includes('바이크') || n.includes('싸이클')) return '실내 자전거';
  if (n.includes('로잉머신')) return '로잉 머신';
  if (n.includes('스텝밀') || n.includes('일립티컬') || n.includes('스키머신')) return '유산소 머신';
  if (n.includes('줄넘기')) return '줄넘기';
  return '';
}

